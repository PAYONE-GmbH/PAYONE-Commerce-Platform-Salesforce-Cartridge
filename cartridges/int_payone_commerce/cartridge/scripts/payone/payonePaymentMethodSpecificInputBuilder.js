/**
 * Resolves the builder function for a supported payment method.
 *
 * @param {string} buildKey - Configured builder key.
 * @returns {Function|null} Builder function or null.
 */
function getPaymentMethodBuilder(buildKey) {
    switch (buildKey) {
        case 'card':
            return buildCardPaymentMethodSpecificInput;
        case 'sepa':
            return buildSepaPaymentMethodSpecificInput;
        case 'secureinvoice':
            return buildSecureInvoicePaymentMethodSpecificInput;
        case 'secureinstallment':
            return buildSecureInstallmentPaymentMethodSpecificInput;
        case 'securedirectdebit':
            return buildSecureDirectDebitPaymentMethodSpecificInput;
        case 'googlepay':
            return buildGooglePayPaymentMethodSpecificInput;
        case 'paypal':
            return buildPayPalPaymentMethodSpecificInput;
        case 'wero':
            return buildWeroPaymentMethodSpecificInput;
        case 'storepay':
            return buildStorePayPaymentMethodSpecificInput;
        default:
            return null;
    }
}

/**
 * Builds PAYONE payment-method specific input from posted checkout data.
 *
 * @param {string} paymentMethodId - SFCC payment method id.
 * @param {string} tokenInformation - Tokenized payment information.
 * @param {Object} [req] - SFRA request object.
 * @returns {Object|null} PAYONE paymentMethodSpecificInput payload.
 */
function buildPaymentMethodSpecificInput(paymentMethodId, tokenInformation, req) {
    var config = getPaymentMethodConfig(paymentMethodId);
    var builder;

    if (!config) {
        return null;
    }

    builder = getPaymentMethodBuilder(config.buildKey);

    if (!builder) {
        return null;
    }

    return builder({
        req: req,
        paymentMethodId: paymentMethodId,
        tokenInformation: tokenInformation
    });
}


/**
 * Indicates whether the selected method requires checkout-only customer override data.
 *
 * @param {string} paymentMethodId - SFCC payment method id.
 * @returns {boolean} True when DOB/phone data must be collected from the form.
 */
function requiresCustomerOverride(paymentMethodId) {
    return !!(DATE_OF_BIRTH_METHODS[paymentMethodId] || PHONE_NUMBER_METHODS[paymentMethodId]);
}

/**
 * Returns the request parameter name generated by the SFCC form framework.
 *
 * @param {string} formId - SFCC form id.
 * @param {string} fieldId - SFCC field id.
 * @returns {string} Request parameter name.
 */
function getFormFieldName(formId, fieldId) {
    return 'dwfrm_' + formId + '_' + fieldId;
}

/**
 * Returns the payment-method configuration when implemented.
 *
 * @param {string} paymentMethodId - SFCC payment method id.
 * @returns {Object|null} Method configuration or null.
 */
function getPaymentMethodConfig(paymentMethodId) {
    return SUPPORTED_PAYMENT_METHODS[paymentMethodId] || null;
}

/**
 * Indicates whether the selected payment method has an implemented authorization input mapping.
 *
 * @param {string} paymentMethodId - SFCC payment method id.
 * @returns {boolean} True when implemented.
 */
function supportsPaymentMethod(paymentMethodId) {
    return !!getPaymentMethodConfig(paymentMethodId);
}

/**
 * Reads a posted field for the selected method from the request.
 *
 * @param {Object} req - SFRA request object.
 * @param {string} paymentMethodId - SFCC payment method id.
 * @param {string} fieldId - SFCC field id.
 * @returns {string|null} Posted field value or null.
 */
function getPostedField(req, paymentMethodId, fieldId) {
    var config = getPaymentMethodConfig(paymentMethodId);
    var fieldName;

    if (!config || !req || !req.form) {
        return null;
    }

    fieldName = getFormFieldName(config.formId, fieldId);

    return req.form[fieldName] || null;
}

/**
 * Reads a mandatory posted field for the selected method.
 *
 * @param {Object} req - SFRA request object.
 * @param {string} paymentMethodId - SFCC payment method id.
 * @param {string} fieldId - SFCC field id.
 * @returns {string|null} Posted field value or null.
 */
function getRequiredPostedField(req, paymentMethodId, fieldId) {
    return PayoneCommonUtils.trimString(getPostedField(req, paymentMethodId, fieldId), true);
}

/**
 * Reads a billing form field value safely.
 *
 * @param {Object} billingForm - SFRA billing form object.
 * @param {string[]} fieldPath - Nested form path.
 * @returns {string|null} Trimmed field value or null.
 */
function getBillingFormValue(billingForm, fieldPath) {
    var currentField = billingForm;
    var i;

    for (i = 0; currentField && fieldPath && i < fieldPath.length; i += 1) {
        currentField = currentField[fieldPath[i]];
    }

    return PayoneCommonUtils.trimString(
        currentField && Object.prototype.hasOwnProperty.call(currentField, 'value')
            ? currentField.value
            : null
    );
}


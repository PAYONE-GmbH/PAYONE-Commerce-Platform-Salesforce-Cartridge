/**
* Builds the Apple Pay specific input object required for Payone payment authorization.
*
* @param {dw.order.Order} order - The order object containing payment instruments and order details.
* @param {Object} context - The context object containing Apple Pay payment data and method information.
* @returns {Object} An object containing the mobilePaymentMethodSpecificInput structure for Apple Pay authorization.
*/
function buildApplePaySpecificInput(order, context) {
    var Site = require('dw/system/Site').getCurrent();
    var payoneCommerceApplePayHelper = require('*/cartridge/scripts/helpers/payoneCommerceApplePayHelper.js');
    var payoneCheckoutAuthorizationHelper = require('*/cartridge/scripts/payone/payoneCheckoutAuthorizationHelper');

    var safeContext = context || {};
    var paymentInstruments = order.getPaymentInstruments();
    var paymentInstrument = paymentInstruments.length ? paymentInstruments[0] : null;

    return {
        mobilePaymentMethodSpecificInput: {
            paymentProductId: PAYMENT_PRODUCT_IDS.APPLE_PAY,
            authorizationMode: 'PRE_AUTHORIZATION',
            encryptedPaymentData: safeContext.paymentData.data,
            publicKeyHash: safeContext.paymentData.header.publicKeyHash,
            ephemeralKey: safeContext.paymentData.header.ephemeralPublicKey,
            threeDSecure: {
                redirectionData: {
                    returnUrl: payoneCheckoutAuthorizationHelper.buildReturnUrl(order, paymentInstrument)
                }
            },
            paymentProduct302SpecificInput: {
                integrationType: payoneCommerceApplePayHelper.getIntegrationType(),
                network: safeContext.paymentMethod.network.toUpperCase(),
                token: {
                    version: safeContext.paymentData.version.toUpperCase(),
                    signature: safeContext.paymentData.signature,
                    header: {
                        transactionId: safeContext.paymentData.header.transactionId
                    }
                },
                domainName: Site.getHttpsHostName(),
                displayName: Site.getName()
            }
        }
    };
}


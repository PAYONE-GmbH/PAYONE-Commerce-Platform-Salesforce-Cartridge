/**
 * Normalizes posted token information to the PAYONE paymentProcessingToken string.
 *
 * @param {string} tokenInformation - Raw posted token payload.
 * @returns {string|null} Payment processing token.
 */
function normalizeTokenInformation(tokenInformation) {
    var parsedTokenInformation;
    var normalizedToken;

    normalizedToken = PayoneCommonUtils.trimString(tokenInformation, true);

    if (!normalizedToken) {
        return null;
    }

    if (normalizedToken.charAt(0) === '{' || normalizedToken.charAt(0) === '[') {
        parsedTokenInformation = PayoneCommonUtils.parseJson(normalizedToken);
        normalizedToken = PayoneCommonUtils.trimString(
            parsedTokenInformation && (
                parsedTokenInformation.tokenValue
                || parsedTokenInformation.paymentProcessingToken
            ),
            true
        );
    }

    return normalizedToken;
}

/**
 * Parses a posted JSON payload into an object.
 *
 * @param {string} payload - Raw posted payload.
 * @returns {Object|null} Parsed object or null.
 */
function parsePostedJson(payload) {
    var normalizedPayload = PayoneCommonUtils.trimString(payload, true);

    if (!normalizedPayload) {
        return null;
    }

    return PayoneCommonUtils.parseJson(normalizedPayload);
}

/**
 * Maps a hosted-tokenization card type to a PAYONE payment product id.
 *
 * @param {string} cardType - Hosted tokenizer card type.
 * @returns {number|null} PAYONE payment product id.
 */
function getCardPaymentProductId(cardType) {
    var normalizedCardType = PayoneCommonUtils.trimString(cardType, true);

    if (!normalizedCardType) {
        return null;
    }

    return CARD_PAYMENT_PRODUCT_IDS[normalizedCardType.toLowerCase()] || null;
}

/**
 * Extracts the Google Pay encrypted payment data token from a posted payment data payload.
 *
 * @param {string} tokenInformation - Raw posted Google Pay payload.
 * @returns {string|null} Encrypted payment data token.
 */
function getGooglePayEncryptedPaymentData(tokenInformation) {
    var parsedTokenInformation = parsePostedJson(tokenInformation);
    var paymentToken;

    if (!parsedTokenInformation) {
        paymentToken = normalizeTokenInformation(tokenInformation);

        return paymentToken
            ? StringUtils.encodeBase64(paymentToken, 'UTF-8')
            : null;
    }

    paymentToken = PayoneCommonUtils.trimString(
        parsedTokenInformation.paymentMethodData
            && parsedTokenInformation.paymentMethodData.tokenizationData
            && parsedTokenInformation.paymentMethodData.tokenizationData.token,
        true
    );

    if (!paymentToken) {
        return null;
    }

    return StringUtils.encodeBase64(paymentToken, 'UTF-8');
}

/**
 * Extracts the approved PayPal checkout payload from the posted hidden field.
 *
 * @param {string} tokenInformation - Raw posted PayPal payload.
 * @returns {Object|null} Approved PayPal payload or null.
 */
function getPayPalApprovalData(tokenInformation) {
    var parsedTokenInformation = parsePostedJson(tokenInformation);

    if (!parsedTokenInformation || !parsedTokenInformation.approved) {
        return null;
    }

    return parsedTokenInformation;
}

/**
 * Extracts the selected Secure Installment context payload from the posted hidden field.
 *
 * @param {string} tokenInformation - Raw hidden-field payload.
 * @returns {Object|null} Selected Secure Installment data or null.
 */
function getSecureInstallmentSelectionData(tokenInformation) {
    var parsedTokenInformation = parsePostedJson(tokenInformation);

    if (!parsedTokenInformation || !parsedTokenInformation.contextKey || !parsedTokenInformation.installmentOptionId) {
        return null;
    }

    return parsedTokenInformation;
}

/**
 * Builds a PAYONE-compatible birth date from split form fields.
 *
 * @param {string|number} day - Day value.
 * @param {string|number} month - Month value.
 * @param {string|number} year - Year value.
 * @returns {string|null} Birth date in YYYYMMDD format.
 */
function buildBirthDateString(day, month, year) {
    var parsedDay = PayoneCommonUtils.toInt(day);
    var parsedMonth = PayoneCommonUtils.toInt(month);
    var parsedYear = PayoneCommonUtils.toInt(year);

    if (!parsedDay || !parsedMonth || !parsedYear) {
        return null;
    }

    if (parsedDay < 1 || parsedDay > 31 || parsedMonth < 1 || parsedMonth > 12 || parsedYear < 1900 || parsedYear > 2100) {
        return null;
    }

    return String(parsedYear)
        + ('0' + parsedMonth).slice(-2)
        + ('0' + parsedDay).slice(-2);
}

/**
 * Builds a bank-account information object when the required fields are present.
 *
 * @param {string} iban - IBAN value.
 * @param {string} accountHolder - Account holder value.
 * @returns {Object|null} PAYONE bankAccountInformation object.
 */
function buildBankAccountInformation(iban, accountHolder) {
    var normalizedIban = PayoneCommonUtils.trimString(iban, true);
    var normalizedAccountHolder = PayoneCommonUtils.trimString(accountHolder, true);

    if (!normalizedIban || !normalizedAccountHolder) {
        return null;
    }

    return {
        iban: normalizedIban,
        accountHolder: normalizedAccountHolder
    };
}

/**
 * Builds an account-holder name from posted billing address fields.
 *
 * @returns {string|null} Billing full name or null.
 */
function getBillingAccountHolder() {
    var billingForm = server.forms.getForm('billing');
    var firstName = getBillingFormValue(billingForm, ['addressFields', 'firstName']);
    var lastName = getBillingFormValue(billingForm, ['addressFields', 'lastName']);

    return [firstName, lastName].filter(function (value) {
        return !!value;
    }).join(' ') || null;
}

/**
 * Returns the payment-method specific birth-date field ids.
 *
 * @param {string} paymentMethodId - SFCC payment method id.
 * @returns {{day:string, month:string, year:string}} Birth-date field ids.
 */
function getBirthDateFieldIds(paymentMethodId) {
    if (paymentMethodId === 'PAYONE_COMMERCE_SECURE_INVOICE') {
        return {
            day: 'secureInvoiceBirthDay',
            month: 'secureInvoiceBirthMonth',
            year: 'secureInvoiceBirthYear'
        };
    }

    if (paymentMethodId === 'PAYONE_COMMERCE_SECURE_INSTALLMENT') {
        return {
            day: 'secureInstallmentBirthDay',
            month: 'secureInstallmentBirthMonth',
            year: 'secureInstallmentBirthYear'
        };
    }

    return {
        day: 'secureDebitBirthDay',
        month: 'secureDebitBirthMonth',
        year: 'secureDebitBirthYear'
    };
}

/**
 * Builds a lightweight customer-data override payload from checkout form fields.
 *
 * @param {string} paymentMethodId - SFCC payment method id.
 * @param {Object} req - SFRA request object.
 * @returns {Object|null} Customer/contact override payload or null.
 */
function buildCustomerOverride(paymentMethodId, req) {
    var customerOverride = {};
    var birthDate;
    var birthDateFieldIds;
    var phoneFieldId;
    var emailAddress;

    if (DATE_OF_BIRTH_METHODS[paymentMethodId]) {
        birthDateFieldIds = getBirthDateFieldIds(paymentMethodId);
        birthDate = buildBirthDateString(
            getPostedField(req, paymentMethodId, birthDateFieldIds.day),
            getPostedField(req, paymentMethodId, birthDateFieldIds.month),
            getPostedField(req, paymentMethodId, birthDateFieldIds.year)
        );

        if (!birthDate) {
            return null;
        }

        customerOverride.personalInformation = {
            dateOfBirth: birthDate
        };
    }

    phoneFieldId = PHONE_NUMBER_METHODS[paymentMethodId];
    if (phoneFieldId) {
        customerOverride.contactDetails = {
            phoneNumber: getRequiredPostedField(req, paymentMethodId, phoneFieldId)
        };

        if (!customerOverride.contactDetails.phoneNumber) {
            return null;
        }
    }

    if (paymentMethodId === 'PAYONE_COMMERCE_SECURE_INSTALLMENT') {
        emailAddress = getBillingFormValue(server.forms.getForm('billing'), ['contactInfoFields', 'email']);

        if (emailAddress) {
            customerOverride.contactDetails = customerOverride.contactDetails || {};
            customerOverride.contactDetails.emailAddress = emailAddress;
        }
    }

    return Object.keys(customerOverride).length ? customerOverride : null;
}

/**
 * Builds PAYONE secured-installment input.
 *
 * @param {Object} context - Builder context.
 * @returns {Object|null} PAYONE financing input payload.
 */
function buildSecureInstallmentPaymentMethodSpecificInput(context) {
    var safeContext = context || {};
    var selectionData = getSecureInstallmentSelectionData(safeContext.tokenInformation);
    var bankAccountInformation = buildBankAccountInformation(
        getPostedField(safeContext.req, safeContext.paymentMethodId, 'secureInstallmentIban'),
        getBillingAccountHolder(safeContext.req)
    );

    if (!selectionData || !bankAccountInformation) {
        return null;
    }

    return {
        financingPaymentMethodSpecificInput: {
            paymentProductId: PAYMENT_PRODUCT_IDS.SECURED_INSTALLMENT,
            paymentProduct3391SpecificInput: {
                installmentOptionId: selectionData.installmentOptionId,
                bankAccountInformation: bankAccountInformation
            }
        }
    };
}

/**
 * Builds PAYONE card payment input.
 *
 * @param {Object} context - Builder context.
 * @returns {Object|null} PAYONE card payment input payload.
 */
function buildCardPaymentMethodSpecificInput(context) {
    var safeContext = context || {};
    var paymentProcessingToken = normalizeTokenInformation(safeContext.tokenInformation);
    var paymentProductId = getCardPaymentProductId(getCardType(safeContext.req, safeContext.paymentMethodId));

    if (!paymentProcessingToken || !paymentProductId) {
        return null;
    }

    return {
        cardPaymentMethodSpecificInput: {
            paymentProcessingToken: paymentProcessingToken,
            paymentProductId: paymentProductId
        }
    };
}

